import { checkAnswer } from '../src/lib/maths/check'
import type { Answer } from '../src/lib/maths/types'

let fails = 0
function t(a: Answer, input: string, expectCorrect: boolean, expectInvalid = false) {
  const r = checkAnswer(a, input)
  const ok = r.correct === expectCorrect && !!r.invalid === expectInvalid
  if (!ok) {
    fails++
    console.log('FAIL', JSON.stringify(a), JSON.stringify(input), '=>', r)
  }
}

